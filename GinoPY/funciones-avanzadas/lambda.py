
#Lambda simple
suma = lambda a, b: a + b
print(suma(5, 5))


#Lambda sin parametros
saludo = lambda: "Hola mundo"
print(saludo())


#Lambda con parametros
cuadrado = lambda x: x**2
print(cuadrado(4))  # 16


#Lambda con  multiples parametros
multiplicar = lambda a, b, c: a * b * c
print(multiplicar(2, 3, 4))  # 24


